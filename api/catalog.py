"""Loader for the generated `config/field_catalog.json` (+ the other config files).

Read-only helpers shared by the API, the mock providers and tests. The catalog
itself is generated by `scripts/gen_catalog.py`; never edit the JSON by hand.
"""
from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict

CONFIG_DIR = Path(__file__).resolve().parents[1] / "config"

FieldType = Literal["bool", "int", "float", "enum", "str"]


class CatalogField(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    key: str
    type: FieldType
    engine_field: str | None
    enum_values: list[str] | None
    enum_labels_es: dict[str, str] | None
    enum_labels_en: dict[str, str] | None
    label_es: str
    label_en: str
    group: str
    askable: bool
    lexicon: dict[str, list[str]]


class Catalog(BaseModel):
    model_config = ConfigDict(extra="ignore", frozen=True)

    version: int
    groups: list[dict[str, str]]
    negation_cues: list[str]
    negation_window_tokens: int
    fields: list[CatalogField]

    @property
    def keys(self) -> list[str]:
        return [f.key for f in self.fields]

    def get(self, key: str) -> CatalogField:
        for f in self.fields:
            if f.key == key:
                return f
        raise KeyError(key)


@lru_cache(maxsize=1)
def load_catalog() -> Catalog:
    return Catalog.model_validate_json((CONFIG_DIR / "field_catalog.json").read_text())


@lru_cache(maxsize=None)
def load_config(name: str) -> Any:
    return json.loads((CONFIG_DIR / name).read_text())


def normalize(text: str) -> str:
    """Lowercase, strip accents, collapse whitespace (SPECS §6.1 E-quote)."""
    decomposed = unicodedata.normalize("NFD", text.lower())
    stripped = "".join(ch for ch in decomposed if unicodedata.category(ch) != "Mn")
    return re.sub(r"\s+", " ", stripped).strip()
