// Copies the UI-relevant part of ../config/field_catalog.json (keys, types,
// enum values, ES/EN labels, groups) into lib/field-catalog.json.
// The web app cannot import files outside web/ on Vercel, so the copy is
// committed. Run `pnpm sync:catalog` after scripts/gen_catalog.py changes;
// `--check` fails if the copy is stale.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, "..", "..", "config", "field_catalog.json")
const dst = join(here, "..", "lib", "field-catalog.json")

const catalog = JSON.parse(readFileSync(src, "utf8"))
const slim = {
  _doc: "GENERATED by web/scripts/sync-catalog.mjs from config/field_catalog.json. Do not edit.",
  version: catalog.version,
  groups: catalog.groups,
  fields: catalog.fields.map((f) => ({
    key: f.key,
    type: f.type,
    group: f.group,
    askable: f.askable,
    label_es: f.label_es,
    label_en: f.label_en,
    enum_values: f.enum_values ?? null,
    enum_labels_es: f.enum_labels_es ?? null,
    enum_labels_en: f.enum_labels_en ?? null,
  })),
}
const out = JSON.stringify(slim, null, 2) + "\n"

if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(dst, "utf8")
  } catch {}
  if (current !== out) {
    console.error("lib/field-catalog.json is stale: run `pnpm sync:catalog`")
    process.exit(1)
  }
} else {
  writeFileSync(dst, out)
  console.log(`wrote ${dst} (${slim.fields.length} fields)`)
}
