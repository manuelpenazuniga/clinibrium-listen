#!/usr/bin/env bash
# Generate web/lib/contracts.ts from api/listen/contracts.py (SPECS §5.2).
# pydantic JSON Schema → json-schema-to-typescript. Nobody edits the output by hand.
#   ./scripts/gen_contracts.sh          write web/lib/contracts.ts
#   ./scripts/gen_contracts.sh --check  fail if it is stale (CI)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/web/lib/contracts.ts"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

(cd "$ROOT" && uv run --quiet python scripts/dump_contracts_schema.py) > "$TMP/contracts.schema.json"
(cd "$ROOT/web" && pnpm exec json2ts \
  --input "$TMP/contracts.schema.json" \
  --output "$TMP/contracts.body.ts" \
  --unreachableDefinitions \
  --additionalProperties false \
  --bannerComment "" \
  --no-style.singleQuote)

{
  echo "/* eslint-disable */"
  echo "// GENERATED by scripts/gen_contracts.sh from api/listen/contracts.py — DO NOT EDIT."
  echo "// Frozen after Phase 0 (SPECS §0.3). Change the pydantic models, then regenerate."
  echo
  cat "$TMP/contracts.body.ts"
} > "$TMP/contracts.ts"

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -q "$TMP/contracts.ts" "$OUT" >/dev/null 2>&1; then
    echo "web/lib/contracts.ts is stale: run scripts/gen_contracts.sh" >&2
    exit 1
  fi
  exit 0
fi
cp "$TMP/contracts.ts" "$OUT"
echo "wrote web/lib/contracts.ts"
